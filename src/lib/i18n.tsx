export type Key = keyof typeof D;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }>({
  lang: "ru", setLang: () => {}, t: (k) => D[k][0],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ru");
  useEffect(() => {
    try { const s = localStorage.getItem("zw-lang"); if (s === "kk" || s === "ru") setLangState(s); } catch {}
  }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem("zw-lang", l); } catch {} };
  const t = (k: Key) => D[k][lang === "kk" ? 1 : 0];
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);

/** Название сущности на текущем языке */
export function nm(x: { name_ru: string; name_kk?: string | null } | undefined | null, lang: Lang) {
  if (!x) return "—";
  return lang === "kk" && x.name_kk ? x.name_kk : x.name_ru;
}

const MON_RU = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"];
const MON_KK = ["қаңтар", "ақпан", "наурыз", "сәуір", "мамыр", "маусым", "шілде", "тамыз", "қыркүйек", "қазан", "қараша", "желтоқсан"];
export function monthName(iso: string, lang: Lang, withYear = true) {
  const m = Number(iso.slice(5, 7)) - 1;
  const n = (lang === "kk" ? MON_KK : MON_RU)[m];
  return withYear ? `${n} ${iso.slice(0, 4)}` : n;
}
export function dateRu(iso: string) {
  return `${iso.slice(8, 10)}.${iso.slice(5, 7)}.${iso.slice(0, 4)}`;
}

/** «1 запись», «3 записи», «43 записи», «25 записей» */
export function entriesLabel(n: number, lang: Lang) {
  if (lang === "kk") return `${n} жазба`;
  const a = n % 10, b = n % 100;
  return `${n} ${a === 1 && b !== 11 ? "запись" : a >= 2 && a <= 4 && (b < 12 || b > 14) ? "записи" : "записей"}`;
}
